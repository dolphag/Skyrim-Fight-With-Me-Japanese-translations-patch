# --- 折り返し対策 ---
# Paragraph(折り返し描画)はASCIIスペースの位置でしか折り返さないため、日本語の長文が枠からはみ出す。
# 1) 読点・句点・コロンの後ろに半角スペースを入れる。
# 2) それでも1区間が MAXSEG 文字を超える場合、助詞の後ろ・「（」の前など自然な切れ目で、中央に近い所に追加で入れる。
#    ASCIIどうしの間・{...}の内側・閉じ括弧/句読点の前には入れない。
import re as _re
MAXSEG = 18          # 1区間の最大幅(全角1文字=1、{..}=2)。ガイドの枠は全角約25文字
try:
    from janome.tokenizer import Tokenizer as _Tok     # pip install janome (ビルド時のみ必要)
except ImportError:
    raise SystemExit('janome が必要です(折り返し用スペースの位置を決めるため): pip install janome')
_tok = _Tok()
_UNIT = _re.compile(r'\{[^}]*\}|.', _re.S)
def _cands(units):
    """単位列の中で、文節の切れ目(助詞の後ろ・「（」の前)になる位置(= 空白を入れる添字)の集合"""
    masked = ''.join('〇' if u[0] == '{' else u for u in units)
    ok = set()
    if _tok:
        pos = 0
        for t in _tok.tokenize(masked):
            pos += len(t.surface)
            if t.part_of_speech.startswith('助詞'): ok.add(pos)
    for i, u in enumerate(units):
        if u == '（': ok.add(i)
    res = []
    for i in ok:
        if i <= 0 or i >= len(units): continue
        a, b = units[i-1], units[i]
        if a.isascii() and b.isascii(): continue
        if b in '。、）」』・：:,.!?%％' or a in '（「『': continue
        res.append(i)
    return res
def _w(units): return sum(2 if u[0] == '{' else 1 for u in units)
def _split_units(units):
    if _w(units) <= MAXSEG: return [units]
    c = _cands(units)
    if not c: return [units]
    tot = _w(units)
    i = min(c, key=lambda i: abs(_w(units[:i]) - tot/2))
    return _split_units(units[:i]) + _split_units(units[i:])
def _split_seg(seg):
    return [''.join(x) for x in _split_units(_UNIT.findall(seg))]
def _wrapfix(v):
    if len(v) < 18 or '\n' in v: return v
    v = _re.sub(r'([、。：])(?=[^\s])', r'\1 ', v)
    out = []
    for seg in v.split(' '):
        out += _split_seg(seg)
    return ' '.join(out)

